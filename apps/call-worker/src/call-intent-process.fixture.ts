import { open } from 'node:fs/promises';
import { createServer, type IncomingMessage, type ServerResponse } from 'node:http';

import { prisma } from '@dentabill/db';
import { createLogger } from '@dentabill/logger';
import { type RetellPort } from '@dentabill/payer-ivr';
import { type CallJobResult } from '@dentabill/queue';
import { z } from 'zod';

import { loadWorkerEnv } from './env.js';
import { createCallJobHandler } from './handler.js';

const commandSchema = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('provider.start'),
    ledgerPath: z.string(),
    retellCallId: z.string(),
    response: z.enum(['hold', 'accept']),
  }),
  z.object({ type: z.literal('provider.stop') }),
  z.object({
    type: z.literal('worker.run'),
    organizationId: z.string(),
    claimId: z.string(),
    queueKey: z.string(),
    providerUrl: z.string().url(),
    now: z.string().datetime().optional(),
  }),
]);

export type IntentFixtureCommand = z.infer<typeof commandSchema>;
export type IntentFixtureReply =
  | { type: 'provider.ready'; pid: number; url: string }
  | { type: 'provider.accepted'; pid: number; intentId: string }
  | { type: 'worker.waiting'; pid: number }
  | { type: 'worker.result'; pid: number; result: CallJobResult; startCount: number }
  | { type: 'fixture.failed'; message: string };

async function send(reply: IntentFixtureReply): Promise<void> {
  await new Promise<void>((resolve, reject) => {
    if (!process.send) {
      reject(new Error('Fixture requires IPC.'));
      return;
    }
    process.send(reply, (error) => {
      if (error) reject(error);
      else resolve();
    });
  });
}

async function command(): Promise<IntentFixtureCommand> {
  const value = await new Promise<unknown>((resolve) => {
    process.once('message', (message: unknown) => {
      resolve(message);
    });
  });
  return commandSchema.parse(value);
}

async function runProvider(
  initial: Extract<IntentFixtureCommand, { type: 'provider.start' }>,
): Promise<void> {
  async function accept(request: IncomingMessage, response: ServerResponse): Promise<void> {
    if (request.method !== 'POST' || request.url !== '/synthetic-create') {
      response.writeHead(404).end();
      return;
    }
    const chunks: Buffer[] = [];
    for await (const chunk of request) chunks.push(Buffer.from(chunk as Uint8Array));
    const { intentId } = z
      .object({ intentId: z.string().min(1) })
      .parse(JSON.parse(Buffer.concat(chunks).toString('utf8')) as unknown);
    // No provider deduplication: every create request produces another ledger entry.
    // The path is generated by the parent test inside its private temporary directory.
    // eslint-disable-next-line security/detect-non-literal-fs-filename
    const ledger = await open(initial.ledgerPath, 'a', 0o600);
    try {
      await ledger.writeFile(
        `${JSON.stringify({ intentId, retellCallId: initial.retellCallId })}\n`,
      );
      await ledger.sync();
    } finally {
      await ledger.close();
    }
    await send({ type: 'provider.accepted', pid: process.pid, intentId });
    if (initial.response === 'accept') {
      response.writeHead(201, { 'content-type': 'application/json' });
      response.end(
        JSON.stringify({ call_id: initial.retellCallId, queued_at: '2026-10-13T12:00:00.000Z' }),
      );
    }
    // In hold mode acceptance is durable, but the worker never receives a response.
  }
  const server = createServer((request, response) => {
    void accept(request, response).catch(() => {
      response.writeHead(500).end();
      void send({ type: 'fixture.failed', message: 'Synthetic provider acceptance failed.' });
    });
  });
  await new Promise<void>((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  const address = server.address();
  if (address === null || typeof address === 'string') throw new Error('Missing loopback address.');
  const stop = command();
  await send({
    type: 'provider.ready',
    pid: process.pid,
    url: `http://127.0.0.1:${String(address.port)}/synthetic-create`,
  });
  if ((await stop).type !== 'provider.stop') throw new Error('Unexpected provider command.');
  server.closeAllConnections();
  await new Promise<void>((resolve, reject) => {
    server.close((error) => {
      if (error) reject(error);
      else resolve();
    });
  });
}

async function runWorker(
  initial: Extract<IntentFixtureCommand, { type: 'worker.run' }>,
): Promise<void> {
  const endpoint = new URL(initial.providerUrl);
  if (endpoint.protocol !== 'http:' || endpoint.hostname !== '127.0.0.1') {
    throw new Error('Synthetic provider must use loopback HTTP.');
  }
  let startCount = 0;
  const retellPort: RetellPort = {
    startCall: async (input) => {
      startCount++;
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ intentId: input.idempotencyKey }),
      });
      if (!response.ok) throw new Error('Synthetic provider rejected request.');
      const body = z
        .object({ call_id: z.string(), queued_at: z.string() })
        .parse(await response.json());
      return { retellCallId: body.call_id, queuedAt: body.queued_at };
    },
    endCall: () => Promise.reject(new Error('Unexpected synthetic hangup.')),
    subscribe: () => {
      void send({ type: 'worker.waiting', pid: process.pid });
      // No lifecycle callback exists. Completion must come from durable DB evidence.
      return () => {
        /* No local event listener was registered. */
      };
    },
  };
  const env = loadWorkerEnv({
    DATABASE_URL: process.env.DATABASE_URL,
    REDIS_URL: 'redis://localhost:6379/14',
    NODE_ENV: 'test',
    RETELL_API_KEY: '',
    DEMO_AUTOPILOT: 'false',
    WORKER_OUTBOUND_NUMBER: '+15555550100',
  });
  const now = initial.now;
  const handler = createCallJobHandler({
    prisma,
    retellPort,
    env,
    logger: createLogger({ level: 'fatal', pretty: false }),
    outboundNumberE164: env.WORKER_OUTBOUND_NUMBER,
    ...(now ? { clock: () => new Date(now) } : {}),
  });
  const job = {
    id: initial.queueKey,
    data: {
      organizationId: initial.organizationId,
      claimId: initial.claimId,
      payerCode: 'DELTA_DENTAL_PPO',
      attemptNumber: 1,
      claimPriority: 80,
      idempotencyKey: initial.queueKey,
    },
  } as Parameters<typeof handler>[0];
  const result = await handler(job, 'synthetic-intent-worker-token');
  await send({ type: 'worker.result', pid: process.pid, result, startCount });
}

try {
  const initial = await command();
  if (initial.type === 'provider.start') await runProvider(initial);
  else if (initial.type === 'worker.run') await runWorker(initial);
  else throw new Error('Unexpected initial fixture command.');
} catch (error) {
  await send({
    type: 'fixture.failed',
    message: error instanceof Error ? error.message : 'Unknown fixture error.',
  });
  process.exitCode = 1;
} finally {
  await prisma.$disconnect();
  if (process.connected) process.disconnect();
}
